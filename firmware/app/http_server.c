// GET /api/incidents — JSON array of records persisted across reboots
// (Core 1 wedges, hardware watchdog resets, OTA rollbacks, manual test
// inserts). Read-only; the POST variant clears them.
static void handle_incidents_get(struct altcp_pcb *pcb) {
    static char buf[3072];
    int off = 0;
    off += snprintf(buf + off, sizeof buf - off, "[");
    unsigned n = incident_log_count();
    for (unsigned i = 0; i < n && off < (int)sizeof buf - 256; i++) {
        const incident_record_t *r = incident_log_get(i);
        if (!r) break;
        // Cause name kept terse; the web renderer can map further.
        const char *cause;
        switch (r->cause) {
            case INCIDENT_BOOT:              cause = "boot";         break;
            case INCIDENT_CORE1_WEDGE:       cause = "core1-wedge";  break;
            case INCIDENT_HW_WATCHDOG_RESET: cause = "hw-watchdog";  break;
            case INCIDENT_OTA_ROLLBACK:      cause = "ota-rollback"; break;
            case INCIDENT_MANUAL:            cause = "manual";       break;
            default:                         cause = "?";            break;
        }
        // Defensive escape: msg can contain " or \ if a future caller
        // forwards an arbitrary string. Replace those with '?'. We
        // don't bother with proper JSON escaping for a forensic field.
        char safe_msg[sizeof r->msg];
        size_t mlen = strnlen(r->msg, sizeof r->msg);
        for (size_t k = 0; k < mlen; k++) {
            char c = r->msg[k];
            safe_msg[k] = (c == '"' || c == '\\' || c < 0x20) ? '?' : c;
        }
        safe_msg[mlen] = '\0';
        off += snprintf(buf + off, sizeof buf - off,
            "%s{\"i\":%u,\"cause\":\"%s\",\"uptime_ms\":%u,"
            "\"c1\":%u,\"heap_used\":%u,\"pcb_active\":%u,"
            "\"binary_version\":\"%u.%u\",\"msg\":\"%s\"}",
            i == 0 ? "" : ",",
            i, cause,
            (unsigned)r->uptime_ms,
            (unsigned)r->c1_value,
            (unsigned)r->heap_used,
            (unsigned)r->pcb_active,
            (unsigned)(r->binary_version >> 16),
            (unsigned)(r->binary_version & 0xFFFFu),
            safe_msg);
    }
    snprintf(buf + off, sizeof buf - off, "]");
    send_json(pcb, "200 OK", buf);
}

// POST /api/incidents
//   ?action=clear → erase the log sector (auth required)
//   ?action=test  → append an INCIDENT_MANUAL record (auth required) —
//                   useful for verifying the flash path end-to-end
//                   without having to actually wedge the device.
static void handle_incidents_post(struct altcp_pcb *pcb, http_conn_t *conn) {
    if (!conn->authenticated) {
        send_error(pcb, "403 Forbidden", "invalid or missing auth token");
        return;
    }
    const char *q = strchr(conn->header_buf, '?');
    bool clear = false, test = false;
    if (q) {
        if (strstr(q, "action=clear")) clear = true;
        else if (strstr(q, "action=test")) test = true;
    }
    if (clear) {
        if (incident_log_clear() == 0) {
            send_json(pcb, "200 OK", "{\"ok\":true,\"action\":\"clear\"}");
        } else {
            send_error(pcb, "500 Internal Server Error", "flash clear failed");
        }
        return;
    }
    if (test) {
        if (incident_log_append(INCIDENT_MANUAL, "manual test entry") == 0) {
            send_json(pcb, "200 OK", "{\"ok\":true,\"action\":\"test\"}");
        } else {
            send_error(pcb, "500 Internal Server Error", "flash append failed");
        }
        return;
    }
    send_error(pcb, "400 Bad Request", "specify ?action=clear or ?action=test");
}

static void handle_upload_begin(struct altcp_pcb *pcb, http_conn_t *conn) {
    if (!conn->authenticated) {
        send_error(pcb, "403 Forbidden", "invalid or missing auth token");
        conn->state = CONN_STATE_DONE;
        return;
    }

    // Three valid request shapes:
    //   X-OTA-Start   → begin a new session, then stream body bytes.
    //   X-OTA-Finish  → stream body bytes into an already-open session,
    //                   and call ota_finish() at end-of-body.
    //   (neither)     → stream body bytes into an already-open session,
    //                   keep it open.
    // Legacy one-shot uploads should set BOTH X-OTA-Start and X-OTA-Finish.
    if (conn->ota_start) {
        ota_err_t err = ota_begin();
        if (err != OTA_OK) {
            send_error(pcb, "500 Internal Server Error", ota_error_string(err));
            conn->state = CONN_STATE_DONE;
            return;
        }
    } else if (!ota_in_progress()) {
        send_error(pcb, "409 Conflict", "no OTA session in progress");
        conn->state = CONN_STATE_DONE;
        return;
    }

    conn->state = CONN_STATE_BODY;
    // Snapshot the ring's drain counter so ota_pump_ack only credits
    // bytes Core 0 drains AFTER this upload started.
    conn->last_acked_drained = ota_ring_total_drained();
    // Register periodic poll. lwIP's TCP slow timer fires every ~500 ms;
    // with peer's window closed (we defer all upload-body acks), normal
    // recv callbacks stop firing — http_poll is what wakes us up to
    // credit drained bytes back into the window.
    altcp_poll(pcb, http_poll, 1);
    DEV_LOG("[ota] upload begin: state→BODY, content_length=%u, poll registered\n",
            (unsigned)conn->content_length);
}

// Credit any bytes Core 0 has drained since the last call back into the
// TCP receive window. Called from both http_recv (catch-up on each new
// pbuf) and http_poll (drives forward progress while peer's window is
// closed). Safe to call any time on the upload conn — caps to u16_t
// chunks if Core 0 got way ahead between calls.
//
// altcp_output() is called AFTER altcp_recved so the window-update
// packet is flushed onto the wire NOW instead of waiting for lwIP's
// silly-window threshold to be met by accumulating credits. Without
// this, small per-poll credits (e.g. 1.5–3 KB per 100 ms) can sit
// in pcb->rcv_wnd unannounced for seconds while the peer is stuck
// in zero-window persist.
static void ota_pump_ack(struct altcp_pcb *pcb, http_conn_t *conn) {
    uint32_t drained_now = ota_ring_total_drained();
    uint32_t newly = drained_now - conn->last_acked_drained;
    if (newly == 0) return;
    while (newly > 0) {
        u16_t chunk = (newly > 0xFFFF) ? 0xFFFF : (u16_t)newly;
        altcp_recved(pcb, chunk);
        newly -= chunk;
        conn->last_acked_drained += chunk;
    }
    // Force the window update onto the wire immediately. Without this,
    // lwIP's silly-window-avoidance can sit on small credits until they
    // accumulate past TCP_WND_UPDATE_THRESHOLD — which never happens
    // for a stalled peer in zero-window persist.
    altcp_output(pcb);
}

// Producer side. Always expects to fully accept `len` into the ring
// because TCP_WND < OTA_RING_SIZE and the peer's window is held closed
// (via deferred altcp_recved) until Core 0 drains. If the ring DOES
// overflow somehow, we've lost bytes (lwIP already TCP-acked them) and
// must abort — the in-flight image would be corrupt.
static size_t handle_upload_data(struct altcp_pcb *pcb, http_conn_t *conn,
                                 const uint8_t *data, size_t len) {
    size_t accepted = ota_write_chunk_ex(data, len);
    if (accepted < len) {
        DEV_LOG("[ota] ring overflow: accepted=%u/%u — TCP_WND vs ring sizing bug\n",
                (unsigned)accepted, (unsigned)len);
        send_error(pcb, "500 Internal Server Error", "ring overflow");
        ota_abort();
        conn->state = CONN_STATE_DONE;
        return accepted;
    }
    conn->body_received += accepted;

    if (conn->content_length > 0 && conn->body_received >= conn->content_length) {
        if (conn->ota_finish) {
            // All body bytes are in the ring (or already flashed). Hand
            // off to the Core-0 pump to drain and finalize. http_poll
            // (registered at handle_upload_begin) wakes on each TCP slow
            // tick to check ota_drain_complete and send the response.
            conn->state = CONN_STATE_DRAINING;
            ota_begin_drain();
        } else {
            // Intermediate chunk — ack with current progress, keep OTA open.
            // Advertise Connection: keep-alive so the client reuses this
            // TCP/TLS pcb for the next chunk. http_recv resets the conn
            // for the next request based on conn->keep_alive.
            char body[96];
            int n = snprintf(body, sizeof(body),
                "{\"ok\":true,\"bytes_written\":%u}", (unsigned)ota_bytes_written());
            conn->keep_alive = true;
            send_response_keepalive(pcb, "200 OK", "application/json", body, (size_t)n);
            conn->state = CONN_STATE_DONE;
        }
    }
    return accepted;
}

static void handle_reboot(struct altcp_pcb *pcb, http_conn_t *conn) {
    if (!conn->authenticated) {
        send_error(pcb, "403 Forbidden", "invalid or missing auth token");
        conn->state = CONN_STATE_DONE;
        return;
    }

    send_json(pcb, "200 OK", "{\"ok\":true,\"message\":\"rebooting\"}");
    conn->state = CONN_STATE_DONE;

    // Reboot after a short delay to let the response send.
    //
    // g_reboot_pending tells main() (on core 0) to stop calling
    // watchdog_update() — rom_reboot / watchdog_reboot program the same
    // watchdog LOAD register to fire the reset after delay_ms, and if the
    // main loop pats the dog during that window the countdown is reset
    // before it can fire. See memory:project_rom_reboot_watchdog_race.
    sleep_ms(200);
    extern volatile bool g_reboot_pending;
    __atomic_store_n(&g_reboot_pending, true, __ATOMIC_RELEASE);
    watchdog_reboot(0, 0, 100);
    // Busy-wait while the watchdog counts down.
    while (1) tight_loop_contents();
}

// Send the log response for a given `since`. Used by both the immediate
// path and the long-poll deadline path. log_out is static because both
// callers run on the lwIP tcpip thread, so calls are serialized.
static void send_log_response(struct altcp_pcb *pcb, uint32_t since) {
    static uint8_t log_out[4096];
    uint32_t next_cursor = since;
    size_t n = log_buffer_read(since, log_out, sizeof(log_out), &next_cursor);

    char hdr[768];
    int hdr_len = snprintf(hdr, sizeof(hdr),
        "HTTP/1.1 200 OK\r\n"
        "Content-Type: text/plain; charset=utf-8\r\n"
        "Content-Length: %u\r\n"
        "X-Log-Cursor: %u\r\n"
        "Cache-Control: no-store\r\n"
        "Connection: close\r\n"
        "%s"
        "Access-Control-Expose-Headers: X-Log-Cursor\r\n"
        "\r\n",
        (unsigned)n, (unsigned)next_cursor, cors_headers);
    // snprintf returns the length it WOULD have written if the buffer were
    // unbounded; clamp so we never tcp_write bytes past the buffer end.
    if (hdr_len < 0) hdr_len = 0;
    if (hdr_len > (int)sizeof(hdr)) hdr_len = (int)sizeof(hdr);
    altcp_write(pcb, hdr, hdr_len, TCP_WRITE_FLAG_COPY);
    if (n > 0) altcp_write(pcb, log_out, n, TCP_WRITE_FLAG_COPY);
    altcp_output(pcb);
}

// Send the streaming-mode response headers — no Content-Length, no
// Transfer-Encoding; the body extends until we close the connection.
// HTTP/1.1 § 3.3.3 case 7 allows this when Connection: close is set, and
// browsers consume it via fetch().body.getReader() with no special framing.
static void send_log_stream_headers(struct altcp_pcb *pcb, uint32_t start_cursor) {
    char hdr[768];
    int hdr_len = snprintf(hdr, sizeof(hdr),
        "HTTP/1.1 200 OK\r\n"
        "Content-Type: text/plain; charset=utf-8\r\n"
        "X-Log-Cursor: %u\r\n"
        "Cache-Control: no-store\r\n"
        // Disables proxy buffering on nginx/caddy paths (harmless otherwise);
        // ensures intermediaries flush each tcp_write through immediately.
        "X-Accel-Buffering: no\r\n"
        "Connection: close\r\n"
        "%s"
        "Access-Control-Expose-Headers: X-Log-Cursor\r\n"
        "\r\n",
        (unsigned)start_cursor, cors_headers);
    if (hdr_len < 0) hdr_len = 0;
    if (hdr_len > (int)sizeof(hdr)) hdr_len = (int)sizeof(hdr);
    altcp_write(pcb, hdr, hdr_len, TCP_WRITE_FLAG_COPY);
    altcp_output(pcb);
}

// Return the chunk of the log ring buffer the caller hasn't seen yet.
// GET /api/log                       → empty body, X-Log-Cursor: <current>.
// GET /api/log?since=N               → bytes [N, next_cursor) immediately.
// GET /api/log?since=N&wait_ms=M     → long-poll: hold up to M ms (≤30_000),
//                                      respond on first byte OR deadline.
// GET /api/log?since=N&stream=1      → persistent stream: connection stays
//                                      open and the firmware writes new
//                                      bytes as conduit_log() produces them,
//                                      until the client closes. Client
//                                      tracks cursor by counting received
//                                      bytes (initial position is the
//                                      X-Log-Cursor header on the response).
// Client updates its cursor from X-Log-Cursor. If the client fell behind
// more than LOG_BUFFER_SIZE bytes the firmware fast-forwards to the oldest
// retained byte.
//
// No auth required — this endpoint is read-only and only exposes printf
// output, which is already echoed on USB serial.
static void handle_log(struct altcp_pcb *pcb, http_conn_t *conn) {
    // Parse ?since=N, ?wait_ms=M, ?stream=1 from the request line.
    uint32_t since = 0;
    uint32_t wait_ms = 0;
    bool have_since = false;
    bool stream = false;
    {
        const char *space = strchr(conn->header_buf, ' ');
        const char *q = space ? strchr(space + 1, '?') : NULL;
        const char *end = space ? strchr(space + 1, ' ') : NULL;
        if (q && end && q < end) {
            const char *p = q + 1;
            while (p < end) {
                if (strncmp(p, "since=", 6) == 0) {
                    since = (uint32_t)strtoul(p + 6, NULL, 10);
                    have_since = true;
                } else if (strncmp(p, "wait_ms=", 8) == 0) {
                    wait_ms = (uint32_t)strtoul(p + 8, NULL, 10);
                    // Cap so a pathological client can't park a TCP PCB
                    // indefinitely. 30s > browser long-poll window (~20s).
                    if (wait_ms > 30000) wait_ms = 30000;
                } else if (strncmp(p, "stream=1", 8) == 0) {
                    stream = true;
                }
                const char *amp = memchr(p, '&', end - p);
                if (!amp) break;
                p = amp + 1;
            }
        }
    }
    if (!have_since) since = log_buffer_total_written();

    if (stream) {
        // Persistent push. Tell the client the starting cursor in headers,
        // then keep the connection open — http_poll drains new bytes onto
        // the wire each tick. Disable Nagle so a single short log line
        // (≪ MSS) doesn't sit in the send buffer waiting for company.
        //
        // Clamp `since` to current total: after a device reboot the
        // browser may carry an old cursor that's far past the now-zeroed
        // ring counter. Storing that stale value as conn->log_since wedges
        // the stream — http_poll calls log_buffer_read which clamps its
        // local since but never writes back, so conn->log_since stays
        // huge and zero-byte reads spin forever until total catches up.
        uint32_t total = log_buffer_total_written();
        if (since > total) since = total;
        send_log_stream_headers(pcb, since);
        conn->log_since = since;
        conn->state = CONN_STATE_STREAMING;
        altcp_nagle_disable(pcb);
        enable_keepalive(pcb);
        register_streaming(pcb, conn);
        g_streams_started_total++;
        altcp_poll(pcb, http_poll, 1);
        return;
    }

    // If the client asked to wait and there's nothing new, park the
    // connection — the tcp_poll callback will resume it when data arrives
    // or the deadline is reached. tcp_poll fires every `interval` ticks of
    // the lwIP coarse timer (TCP_SLOW_INTERVAL, typically 500ms), so
    // interval=1 gives us ~500ms resolution — fine for interactive logs.
    if (wait_ms > 0 && log_buffer_total_written() == since) {
        conn->log_since = since;
        conn->log_deadline = make_timeout_time_ms(wait_ms);
        conn->state = CONN_STATE_WAITING;
        altcp_poll(pcb, http_poll, 1);
        return;
    }

    send_log_response(pcb, since);
    conn->state = CONN_STATE_DONE;
}

