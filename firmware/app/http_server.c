// Turn on TCP keepalive for streaming connections. Without this, a
// vanished client (browser tab put to sleep, OS VPN drop, NAT box
// reboot — anything that drops packets without sending FIN/RST) holds
// a PCB indefinitely; after MEMP_NUM_TCP_PCB such events the device
// stops accepting new connections even though the firmware is healthy.
// Probes start after KEEP_IDLE_MS of silence, retry every KEEP_INTVL_MS
// up to KEEP_CNT failures → vanished client costs ≈ 50 s before the
// PCB is reaped.
//
// Keepalive lives on the TCP pcb, not the altcp wrapper, so we walk
// the altcp inner_conn chain down to the underlying transport. For
// plain HTTP that's one hop (altcp_tcp's state is the tcp_pcb); for
// HTTPS it's altcp_tls → altcp_tcp → tcp_pcb. A NULL return means
// the wrapper layout doesn't match what we expect (e.g. we're inside
// a different altcp transport in the future); skip keepalive in that
// case rather than blow up.
#define HTTP_KEEP_IDLE_MS   30000
#define HTTP_KEEP_INTVL_MS   5000
#define HTTP_KEEP_CNT           4
static struct tcp_pcb *altcp_to_tcp_pcb(struct altcp_pcb *pcb) {
    while (pcb && pcb->inner_conn) pcb = pcb->inner_conn;
    if (!pcb || !pcb->state) return NULL;
    return (struct tcp_pcb *)pcb->state;
}
static void enable_keepalive(struct altcp_pcb *pcb) {
    struct tcp_pcb *tpcb = altcp_to_tcp_pcb(pcb);
    if (!tpcb) return;
    tpcb->so_options |= SOF_KEEPALIVE;
    tpcb->keep_idle  = HTTP_KEEP_IDLE_MS;
    tpcb->keep_intvl = HTTP_KEEP_INTVL_MS;
    tpcb->keep_cnt   = HTTP_KEEP_CNT;
}

void http_server_on_link_down(void) {
    int aborted = 0;
    for (int i = 0; i < STREAM_REG_SIZE; i++) {
        struct altcp_pcb *pcb = stream_registry[i].pcb;
        http_conn_t   *conn = stream_registry[i].conn;
        if (!pcb) continue;
        // Reap every long-lived conn-pool slot when the link drops past
        // the debounce window. Previously only STREAMING / WS were
        // touched, which meant an OTA mid-upload (CONN_STATE_BODY) or
        // its drain phase (CONN_STATE_DRAINING) or a /api/log long-poll
        // (CONN_STATE_WAITING) would stay in the pool until the TCP
        // keepalive timed it out ~50 s later. The browser's reconnect
        // SYNs got RST'd in that window because the pool was full.
        // CONN_STATE_HEADER is left alone — those are mid-receive of a
        // fresh request and either complete fast or get reaped by the
        // recv-callback's NULL-pbuf path once the FIN/RST arrives.
        // CONN_STATE_DONE is past the response and just waiting for
        // close; also fine to abort but cheap to leave.
        if (conn) {
            if (conn->state != CONN_STATE_STREAMING &&
                conn->state != CONN_STATE_WS &&
                conn->state != CONN_STATE_BODY &&
                conn->state != CONN_STATE_DRAINING &&
                conn->state != CONN_STATE_WAITING) continue;
            // If this slot was mid-upload, abort the OTA cleanly so the
            // ring + flash state aren't left half-applied. Mirrors the
            // same check in conn_close() and http_err().
            if ((conn->state == CONN_STATE_BODY ||
                 conn->state == CONN_STATE_DRAINING) && ota_in_progress()) {
                ota_abort();
            }
        }
        note_stream_close(STREAM_CLOSE_LINK_DOWN, conn);
        // Detach all callbacks BEFORE altcp_abort. lwIP fires the err
        // callback synchronously from inside altcp_abort, and we want
        // it to no-op since we're freeing the conn ourselves below.
        altcp_arg(pcb, NULL);
        altcp_recv(pcb, NULL);
        altcp_err (pcb, NULL);
        altcp_poll(pcb, NULL, 0);
        altcp_abort(pcb);
        if (conn) http_conn_free(conn);
        stream_registry[i].pcb  = NULL;
        stream_registry[i].conn = NULL;
        aborted++;
    }
    if (aborted > 0) {
        DEV_LOG("[http] link-down: aborted %d stream PCB%s\n",
               aborted, aborted == 1 ? "" : "s");
    }
}

static void conn_close(struct altcp_pcb *pcb, http_conn_t *conn) {
    unregister_streaming(pcb, conn);
    if (conn) {
        // If OTA was started but connection dropped mid-body or while
        // the ring was still draining, abort it.
        if ((conn->state == CONN_STATE_BODY || conn->state == CONN_STATE_DRAINING)
            && ota_in_progress()) {
            ota_abort();
        }
        http_conn_free(conn);
    }
    altcp_arg(pcb, NULL);
    altcp_recv(pcb, NULL);
    altcp_err(pcb, NULL);
    altcp_poll(pcb, NULL, 0);  // clears any /api/log long-poll callback
    altcp_close(pcb);
}

// Periodic callback for /api/log long-poll waiters and stream pushers.
// Fires every ~500ms (lwIP TCP coarse timer). Runs on the same tcpip thread
// as http_recv, so accessing conn/pcb without extra locking is safe.
//
//   WAITING:   new bytes OR deadline → flush response and close.
//   STREAMING: as long as bytes are available AND tcp_sndbuf has room,
//              copy a chunk onto the wire and advance log_since. The
//              connection stays open until the client closes (FIN/RST,
//              detected by http_recv with a NULL pbuf).
static err_t http_poll(void *arg, struct altcp_pcb *pcb) {
    g_http_poll_fires++;
    http_conn_t *conn = (http_conn_t *)arg;
    if (!conn) return ERR_OK;

    if (conn->state == CONN_STATE_BODY) {
        // Upload in progress. Peer's window stays closed (we defer all
        // body-byte acks until Core 0 drains) — this is the heartbeat
        // that reopens it. Credit any bytes drained since the last
        // visit so the peer can keep sending at Core 0's rate.
        ota_pump_ack(pcb, conn);
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_DRAINING) {
        // OTA body fully received; Core 0 is draining the ring. Catch
        // up any straggling acks (mostly harmless — peer won't send
        // more — but keeps lwIP's bookkeeping clean), then wait for
        // ota_drain_complete to flip true and finalize.
        ota_pump_ack(pcb, conn);
        if (!ota_drain_complete()) return ERR_OK;
        ota_err_t pump_err = ota_last_pump_error();
        if (pump_err != OTA_OK) {
            send_error(pcb, "422 Unprocessable Entity", ota_error_string(pump_err));
            ota_abort();
            conn->state = CONN_STATE_DONE;
            return ERR_OK;
        }
        ota_err_t fin = ota_finalize_after_drain();
        if (fin != OTA_OK) {
            send_error(pcb, "422 Unprocessable Entity", ota_error_string(fin));
            conn->state = CONN_STATE_DONE;
            return ERR_OK;
        }
        // ota_finalize_after_drain does not return on success — the
        // 200 OK response below is unreachable, but kept defensively.
        send_json(pcb, "200 OK", "{\"ok\":true,\"message\":\"update complete, rebooting\"}");
        conn->state = CONN_STATE_DONE;
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_WAITING) {
        bool has_data = (log_buffer_total_written() != conn->log_since);
        bool timed_out = time_reached(conn->log_deadline);
        if (!has_data && !timed_out) return ERR_OK;
        send_log_response(pcb, conn->log_since);
        conn->state = CONN_STATE_DONE;
        conn_close(pcb, conn);
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_WS) {
        // WebSocket periodic drain. ws_server_poll handles ring drains,
        // app-layer PING, idle keepalive, and status pushes — see
        // ws_server.c for the full policy. The opportunistic flush
        // from http_recv handles sub-100 ms responses; this is the
        // background tick for idle clients.
        ws_server_poll(pcb, &conn->ws);
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_STREAMING) {
        u16_t avail = altcp_sndbuf(pcb);
        if (avail == 0) return ERR_OK;  // wait for ACK; retry next poll
        uint32_t total = conn->data_stream
            ? data_buffer_total_written()
            : log_buffer_total_written();
        bool have_real_data = (total != conn->log_since);
        if (have_real_data) {
            // Sized to absorb a full slow-timer tick of telemetry at 40 KB/s
            // (4 KB per 100 ms) with comfortable headroom for ACK/window
            // dynamics. Smaller buffers force the data ring to backlog and
            // eventually overflow → dropped samples → browser sees voids.
            static uint8_t out[8192];
            size_t cap = (avail < sizeof(out)) ? avail : sizeof(out);
            uint32_t next = conn->log_since;
            size_t n = conn->data_stream
                ? data_buffer_read(conn->log_since, out, cap, &next)
                : log_buffer_read(conn->log_since, out, cap, &next);
            // Always advance log_since to whatever the ring reader resolved
            // to — even on n==0. If conn->log_since was past total (stale
            // browser cursor across a reboot), data_buffer_read clamped its
            // local since to total and returned 0; without writing back, we'd
            // spin here until total caught up to the stale value (~10 minutes
            // at 250 Hz). Pair with the entry-side clamp in handle_data /
            // handle_log so the very first poll already starts at a sane cursor.
            conn->log_since = next;
            if (n == 0) return ERR_OK;
            // Known cosmetic glitch on cable-cycle boundary: ~once per cable
            // cycle the browser receives one log line whose first ~12 bytes
            // are the *previous* line's prefix bytes prepended to the new
            // line, e.g. "[702317801]\t02846190]\ttick=663000…" instead of
            // "[702846190]\ttick=663000…". The duplicated chunk is exactly
            // one prefix-length, suggesting an lwIP TCP segment-pool / pcb-
            // reuse race around abort/reconnect that re-emits the tail of a
            // prior tcp_write. log_since arithmetic on our side is correct
            // (advance-before-write here only causes gaps on ERR_MEM, never
            // duplicates). Proving the lwIP cause needs a wire capture across
            // many cycles; for now we suppress the visible artifact in the
            // browser via a renderer guard in web/console.js (strips a stray
            // "<digits>]\t" tail from the parsed msg). Revisit if the
            // duplication ever exceeds one prefix length.
            err_t e = altcp_write(pcb, out, n, TCP_WRITE_FLAG_COPY);
            if (e == ERR_MEM) return ERR_OK;  // sndbuf race — retry next poll
            if (e != ERR_OK) {
                note_stream_close(STREAM_CLOSE_WRITE_ERR, conn);
                g_stream_last_close_err = e;
                conn->state = CONN_STATE_DONE;
                conn_close(pcb, conn);
                return ERR_OK;
            }
            altcp_output(pcb);
            conn->last_tx_at = get_absolute_time();
            return ERR_OK;
        }

        // No real data. Emit a tiny keepalive when the connection has
        // been silent for STREAM_KEEPALIVE_MS so the browser stall
        // watchdog (1 s HTTP, 4 s HTTPS) sees bytes from a
        // quiet-but-healthy device.
        // For data streams: a 16-byte zero-payload record with a
        // reserved msg_id (CONDUIT_DATA_KEEPALIVE_MSG_ID) — the browser
        // parser skips it before chart/store push.
        // For log streams: a single newline — browser drops empty
        // lines at the top of processLine().
        //
        // Tried a per-conn HTTPS variant (3000 ms over TLS to reduce
        // per-record framing/AEAD CPU on the M33). Caused a hard wedge
        // when combined with the four concurrent conns the IDE opens
        // (telemetry, console, status, upload). Reverted to the
        // unconditional 500 ms — the v10.29 known-good cadence.
        // Revisit only with a real load test of the IDE startup path.
        #define STREAM_KEEPALIVE_MS  500
        if (!time_reached(delayed_by_ms(conn->last_tx_at, STREAM_KEEPALIVE_MS))) {
            return ERR_OK;
        }
        if (conn->data_stream) {
            if (avail < CONDUIT_DATA_RECORD_HEADER) return ERR_OK;
            uint8_t hdr[CONDUIT_DATA_RECORD_HEADER];
            hdr[0] = CONDUIT_DATA_MAGIC;
            hdr[1] = CONDUIT_DATA_VERSION;
            hdr[2] = (uint8_t)(CONDUIT_DATA_KEEPALIVE_MSG_ID & 0xFF);
            hdr[3] = (uint8_t)((CONDUIT_DATA_KEEPALIVE_MSG_ID >> 8) & 0xFF);
            hdr[4] = (uint8_t)CONDUIT_DTYPE_U8;
            hdr[5] = 0; hdr[6] = 0;       // n = 0 (LE u16)
            hdr[7] = 0;                   // reserved
            uint64_t now_us = (uint64_t)to_us_since_boot(get_absolute_time());
            for (int i = 0; i < 8; i++) hdr[8 + i] = (uint8_t)(now_us >> (8 * i));
            err_t e = altcp_write(pcb, hdr, sizeof(hdr), TCP_WRITE_FLAG_COPY);
            if (e == ERR_MEM) return ERR_OK;
            if (e != ERR_OK) {
                note_stream_close(STREAM_CLOSE_WRITE_ERR, conn);
                g_stream_last_close_err = e;
                conn->state = CONN_STATE_DONE;
                conn_close(pcb, conn);
                return ERR_OK;
            }
        } else {
            if (avail < 1) return ERR_OK;
            const char nl = '\n';
            err_t e = altcp_write(pcb, &nl, 1, TCP_WRITE_FLAG_COPY);
            if (e == ERR_MEM) return ERR_OK;
            if (e != ERR_OK) {
                note_stream_close(STREAM_CLOSE_WRITE_ERR, conn);
                g_stream_last_close_err = e;
                conn->state = CONN_STATE_DONE;
                conn_close(pcb, conn);
                return ERR_OK;
            }
        }
        altcp_output(pcb);
        conn->last_tx_at = get_absolute_time();
    }
    return ERR_OK;
}

static err_t http_recv(void *arg, struct altcp_pcb *pcb, struct pbuf *p, err_t err) {
    http_conn_t *conn = (http_conn_t *)arg;

    if (!p || err != ERR_OK) {
        // Connection closed by client
        note_stream_close(p ? STREAM_CLOSE_RECV_ERR : STREAM_CLOSE_RECV_EOF, conn);
        if (err != ERR_OK) g_stream_last_close_err = err;
        conn_close(pcb, conn);
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_DONE
        || conn->state == CONN_STATE_WAITING
        || conn->state == CONN_STATE_STREAMING) {
        // DONE: response already sent, just waiting for FIN.
        // WAITING / STREAMING: /api/log connections are server-driven;
        // discard any extra bytes the client pushes (no pipelined requests).
        altcp_recved(pcb, p->tot_len);
        pbuf_free(p);
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_WS) {
        // WebSocket: feed every byte through the frame codec. The
        // codec dispatches complete CMD/PING/CLOSE frames synchronously
        // on this callback — that's the <100 ms inbound latency path
        // (see ws_server.c). altcp_recved is unconditional: WS flow
        // control is application-layer (PING/PONG + ring-drain pacing
        // in ws_server_poll), not TCP window.
        bool keep_open = true;
        for (struct pbuf *q = p; q != NULL && keep_open; q = q->next) {
            keep_open = ws_server_on_bytes(pcb, &conn->ws,
                                           (uint8_t *)conn->header_buf,
                                           HTTP_MAX_HEADER,
                                           (const uint8_t *)q->payload,
                                           q->len);
        }
        altcp_recved(pcb, p->tot_len);
        pbuf_free(p);
        if (!keep_open) {
            note_stream_close(STREAM_CLOSE_WS_PARSE_FAIL, conn);
            conn->state = CONN_STATE_DONE;
            conn_close(pcb, conn);
        }
        return ERR_OK;
    }

    if (conn->state == CONN_STATE_DRAINING) {
        // Body fully received; trailing bytes (FIN piggybacks, peer-side
        // retransmits) ack immediately. ota_pump_ack continues to credit
        // newly drained ring bytes — without it the connection's window
        // would never reopen if the peer sends one more probe.
        ota_pump_ack(pcb, conn);
        altcp_recved(pcb, p->tot_len);
        pbuf_free(p);
        return ERR_OK;
    }

    // For active-upload conns, credit any bytes Core 0 has drained since
    // the last visit. This is the catch-up path on top of http_poll —
    // each new recv (e.g. a window probe from the peer) is also a chance
    // to advance the advertised window.
    if (conn->state == CONN_STATE_BODY) {
        ota_pump_ack(pcb, conn);
    }

    // `immediate_ack` is the bytes whose receipt is unconditional
    // (headers, non-upload routes' bodies). Upload body bytes do NOT
    // accumulate here — they're acked exclusively via ota_pump_ack,
    // paced to Core 0's drain rate. That's the throttle: peer's window
    // shrinks as it sends, only reopens as Core 0 catches up. Sizing
    // invariant: TCP_WND < OTA_RING_SIZE guarantees the ring can always
    // accept whatever the peer can have in flight.
    size_t immediate_ack = 0;

    // Process data from all pbufs in the chain
    for (struct pbuf *q = p; q != NULL; q = q->next) {
        uint8_t *data = (uint8_t *)q->payload;
        uint16_t len = q->len;

        if (conn->state == CONN_STATE_HEADER) {
            // Accumulate headers
            uint16_t space = HTTP_MAX_HEADER - conn->header_len - 1;
            uint16_t copy = (len < space) ? len : space;
            memcpy(conn->header_buf + conn->header_len, data, copy);
            conn->header_len += copy;
            conn->header_buf[conn->header_len] = '\0';

            // Check for end of headers
            char *hdr_end = strstr(conn->header_buf, "\r\n\r\n");
            if (hdr_end) {
                conn->headers_complete = true;
                parse_request_line(conn);

                // Bytes in THIS pbuf consumed as headers vs trailing body.
                // header_total counts from the start of header_buf, but
                // earlier pbufs may have contributed some of those bytes;
                // what matters here is how many of THIS pbuf's bytes were
                // header (immediate ack) vs body (deferred via pump_ack).
                uint32_t header_total = (hdr_end - conn->header_buf) + 4;
                uint32_t body_in_header = conn->header_len - header_total;
                uint32_t body_in_pbuf = body_in_header < len ? body_in_header : len;
                uint32_t header_in_pbuf = len - body_in_pbuf;
                immediate_ack += header_in_pbuf;

                // Handle the request
                if (conn->method == METHOD_OPTIONS) {
                    send_cors_preflight(pcb);
                    conn->state = CONN_STATE_DONE;
                } else if (conn->method == METHOD_GET && conn->route == ROUTE_STATUS) {
                    handle_status(pcb);
                    conn->state = CONN_STATE_DONE;
                } else if (conn->method == METHOD_POST && conn->route == ROUTE_UPLOAD) {
                    handle_upload_begin(pcb, conn);
                    // If still in BODY state, feed leftover data — NOT
                    // counted into immediate_ack (handled by pump_ack).
                    if (conn->state == CONN_STATE_BODY && body_in_pbuf > 0) {
                        handle_upload_data(pcb, conn,
                            (uint8_t *)(hdr_end + 4), body_in_pbuf);
                    } else {
                        // upload_begin failed (403/409/500): body bytes
                        // that piggybacked were consumed into the header
                        // buf and discarded — ack so the window reopens.
                        immediate_ack += body_in_pbuf;
                    }
                } else if (conn->method == METHOD_POST && conn->route == ROUTE_REBOOT) {
                    handle_reboot(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_POST && conn->route == ROUTE_COMMIT) {
                    handle_commit(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_GET && conn->route == ROUTE_LOG) {
                    // handle_log sets state to WAITING (long-poll parked) or
                    // DONE (immediate response) — don't force either here.
                    handle_log(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_GET && conn->route == ROUTE_DATA) {
                    // handle_data may go to STREAMING or DONE.
                    handle_data(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_GET && conn->route == ROUTE_DATA_SCHEMA) {
                    handle_data_schema(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_POST && conn->route == ROUTE_CMD) {
                    handle_cmd(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_GET && conn->route == ROUTE_INCIDENTS) {
                    handle_incidents_get(pcb);
                    conn->state = CONN_STATE_DONE;
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_POST && conn->route == ROUTE_INCIDENTS) {
                    handle_incidents_post(pcb, conn);
                    conn->state = CONN_STATE_DONE;
                    immediate_ack += body_in_pbuf;
                } else if (conn->method == METHOD_GET && conn->route == ROUTE_STREAM) {
                    // handle_ws_upgrade transitions the conn to
                    // CONN_STATE_WS on success and into CONN_STATE_DONE
                    // on a malformed Upgrade. Either way the request
                    // body (if any) is consumed: WebSocket clients
                    // don't send a body on the Upgrade GET.
                    handle_ws_upgrade(pcb, conn);
                    immediate_ack += body_in_pbuf;
                } else {
                    send_error(pcb, "404 Not Found", "not found");
                    conn->state = CONN_STATE_DONE;
                    immediate_ack += body_in_pbuf;
                }
            } else {
                // headers not yet complete — entire pbuf is header bytes
                immediate_ack += len;
            }
        } else if (conn->state == CONN_STATE_BODY) {
            // Stream body data into the OTA ring. NOT counted into
            // immediate_ack — paced via ota_pump_ack.
            handle_upload_data(pcb, conn, data, len);
        } else {
            // State changed mid-loop (e.g. handler set DONE / DRAINING /
            // WAITING / STREAMING). Remaining bytes are not part of an
            // active body stream — ack so the window stays open.
            immediate_ack += len;
        }
    }

    if (immediate_ack > 0) {
        altcp_recved(pcb, (u16_t)immediate_ack);
    }
    pbuf_free(p);

    if (conn->state == CONN_STATE_DONE) {
        if (conn->keep_alive) {
            // Reset for the next request on the same TCP/TLS pcb. Wipe
            // every per-request field; preserve the pcb-level callbacks
            // (already registered) and the auth-pass, since on a single
            // long upload the same client is doing all chunks.
            conn->state           = CONN_STATE_HEADER;
            conn->method          = METHOD_UNKNOWN;
            conn->route           = ROUTE_UNKNOWN;
            conn->ota_start       = false;
            conn->ota_finish      = false;
            conn->keep_alive      = false;
            conn->content_length  = 0;
            conn->body_received   = 0;
            conn->header_len      = 0;
            conn->headers_complete = false;
            conn->authenticated   = false;
        } else {
            conn_close(pcb, conn);
        }
    }

    return ERR_OK;
}

static void http_err(void *arg, err_t err) {
    http_conn_t *conn = (http_conn_t *)arg;
    // lwIP has already freed the pcb by the time err fires, so we can
    // only match the registry entry by conn pointer.
    unregister_streaming(NULL, conn);
    if (conn) {
        // Bucket by err code so /api/status can attribute "session
        // lasted 22 min then died, no close frame" — every code lands
        // as 1006 in the browser, only the device knows which.
        // ERR_RST  = peer sent RST (router NAT eviction, peer crash)
        // ERR_ABRT = lwIP gave up on its own (TCP retransmit limit hit
        //            after RTO backoff exhausted, OR altcp_tls_mbedtls
        //            internally called altcp_abort after a decrypt /
        //            MAC failure — both pass through here as ERR_ABRT)
        // ERR_CLSD = orderly close that took the err path (rare)
        stream_close_reason_t reason;
        switch (err) {
            case ERR_RST:  reason = STREAM_CLOSE_ERR_RST;   break;
            case ERR_ABRT: reason = STREAM_CLOSE_ERR_ABRT;  break;
            case ERR_CLSD: reason = STREAM_CLOSE_ERR_CLSD;  break;
            default:       reason = STREAM_CLOSE_ERR_OTHER; break;
        }
        note_stream_close(reason, conn);
        g_stream_last_close_err = err;

        // Only abort the OTA if THIS conn is the one streaming it
        // (CONN_STATE_BODY = mid-upload). Without that guard, every
        // unrelated reset connection — failed TLS handshakes, stray
        // browser tabs, ERR_ABRT from PCB pool churn — would nuke an
        // active OTA simply because its err callback fired. Mirror the
        // same check `conn_close` already has. Keep the DEV_LOG so a
        // genuine mid-upload abort still leaves a breadcrumb.
        if ((conn->state == CONN_STATE_BODY || conn->state == CONN_STATE_DRAINING)
            && ota_in_progress()) {
            DEV_LOG("[http] mid-upload conn err=%d → ota_abort\n", err);
            ota_abort();
        }
        http_conn_free(conn);
    }
}

static err_t http_accept(void *arg, struct altcp_pcb *pcb, err_t err) {
    g_accepts_total++;
    if (err != ERR_OK || pcb == NULL) {
        return ERR_VAL;
    }

    // Allocate connection state from the static pool (see
    // http_conn_alloc declaration for why this isn't libc calloc).
    http_conn_t *conn = http_conn_alloc();
    if (!conn) {
        altcp_abort(pcb);
        return ERR_MEM;
    }

    conn->state = CONN_STATE_HEADER;
    conn->opened_at = get_absolute_time();

    altcp_arg(pcb, conn);
    altcp_recv(pcb, http_recv);
    altcp_err(pcb, http_err);

    // Lower priority so network stack stays responsive
    altcp_setprio(pcb, TCP_PRIO_MIN);

    return ERR_OK;
}

