// Maximum HTTP header size we'll parse
#define HTTP_MAX_HEADER  2048
// Maximum response size. Sized for /api/status — which is the largest
// fixed-shape body we emit — with the Phase 0 wedge-attribution block
// (core1_iter, http_poll_fires, the close-cause buckets, MEMP pool
// stats, mbedtls slab stats) plus the spliced data_schema for up to
// CONDUIT_DATA_MAX_NAMES channels. 1 KB was silently truncating the
// body mid-string after the diag block landed.
#define HTTP_MAX_RESPONSE 2048

typedef enum {
    CONN_STATE_HEADER,     // Accumulating headers
    CONN_STATE_BODY,       // Receiving POST body
    CONN_STATE_DRAINING,   // OTA body fully received; waiting for Core 0 to flush
                           // ring and run the last flash write before responding
    CONN_STATE_WAITING,    // /api/log long-poll: holding until data or deadline
    CONN_STATE_STREAMING,  // /api/log?stream=1: persistent push of new bytes
    CONN_STATE_WS,         // /api/stream: bidirectional WebSocket. Frame codec
                           // and channel dispatch live in ws_server.{c,h}.
    CONN_STATE_DONE,       // Response sent, waiting for close
} conn_state_t;

typedef enum {
    METHOD_UNKNOWN = 0,
    METHOD_GET,
    METHOD_POST,
    METHOD_OPTIONS,
} http_method_t;

typedef enum {
    ROUTE_UNKNOWN = 0,
    ROUTE_STATUS,
    ROUTE_UPLOAD,
    ROUTE_REBOOT,
    ROUTE_COMMIT,
    ROUTE_LOG,
    ROUTE_DATA,         // /api/data — binary record stream
    ROUTE_DATA_SCHEMA,  // /api/data_schema — id→name JSON
    ROUTE_CMD,          // /api/cmd — POST command dispatch (auth)
    ROUTE_INCIDENTS,    // /api/incidents — GET list / POST clear (auth)
    ROUTE_STREAM,       // /api/stream — bidirectional WebSocket
} route_t;

typedef struct {
    conn_state_t state;
    http_method_t method;
    route_t route;
    bool authenticated;
    bool ota_start;    // X-OTA-Start: 1 — call ota_begin before streaming
    bool ota_finish;   // X-OTA-Finish: 1 — call ota_finish after body
    bool keep_alive;   // Send "Connection: keep-alive"; reset conn for the
                       // next request on the same TCP/TLS pcb instead of
                       // closing. Only ever set by the OTA intermediate-
                       // chunk path; closing is the safe default for
                       // every other endpoint.
    uint32_t content_length;
    uint32_t body_received;
    // OTA upload ack pacing — snapshot of ota_ring_total_drained() at the
    // last altcp_recved call for upload-body bytes. Each tick of http_poll
    // (and each recv cb) computes the delta and acks it, throttling the
    // peer's TCP window to Core 0's drain rate. See ota_pump_ack().
    uint32_t last_acked_drained;
    char header_buf[HTTP_MAX_HEADER];
    uint16_t header_len;
    bool headers_complete;
    // /api/log long-poll state (only meaningful when state == WAITING).
    uint32_t log_since;
    absolute_time_t log_deadline;
    // /api/data stream flag. STREAMING covers both /api/log?stream=1 and
    // /api/data?stream=1; this bit tells http_poll which ring to drain.
    bool data_stream;
    // Wall-clock of the last byte http_poll wrote to this PCB (real
    // record bytes OR a keepalive). When STREAMING ring is empty for
    // STREAM_KEEPALIVE_MS we emit a tiny in-band marker so the
    // browser's 1 s stall watchdog has something to count against —
    // without this, a quiet device looks identical to a wedged TX
    // path and the indicator flaps "no data" forever.
    absolute_time_t last_tx_at;
    // Wall-clock when the TCP/TLS accept fired for this conn. Used by
    // note_stream_close() to compute and stash the age of the most
    // recently closed streaming conn — a 22-min disconnect that lands
    // in stream_close_err_abrt looks very different from a 30-s one,
    // and the bucket alone doesn't carry that signal.
    absolute_time_t opened_at;
    // Per-conn WebSocket state. Only meaningful when state == CONN_STATE_WS;
    // ws_server_on_open() initializes it post-Upgrade. The conn's
    // header_buf (2 KB) doubles as the WS frame reassembly buffer
    // since we're done parsing HTTP requests by the time this is
    // active. See ws_server.h for the full per-conn state shape.
    ws_state_t ws;
} http_conn_t;

